package com.probestack.forgestudio.design.config;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.security.SecurityScheme;

@Configuration
public class SpringDocConfiguration {

    @Bean(name = "com.probestack.forgestudio.design.config.SpringDocConfiguration.apiInfo")
    OpenAPI apiInfo() {
        return new OpenAPI()
                .info(
                        new Info()
                                .title("AI Guardrails")
                                .description("Central governance and safety layer for all AI/LLM interactions within  the ForgeSphere platform. Intercepts every AI request and response to  enforce prompt safety, prevent prompt injection, detect PII leakage,  control costs, audit model usage, and enforce per-team policies.  Sits between MCP Bridge, AI agents, and external LLM providers. ")
                                .contact(
                                        new Contact()
                                                .name("ForgeSphere AI Safety Team")
                                                .email("ai-safety@forgesphere.example.com")
                                )
                                .version("1.0.0")
                )
                .components(
                        new Components()
                                .addSecuritySchemes("bearerAuth", new SecurityScheme()
                                        .type(SecurityScheme.Type.HTTP)
                                        .scheme("bearer")
                                        .bearerFormat("JWT")
                                )
                )
        ;
    }
}
